"""litaddr.py - give the RAM addresses the C code writes as numbers a name (byte-identical by construction).

Run from dualshock/ with the project venv python:
    python tools/litaddr.py header     # config/addrs.txt -> include/re1_addrs.h
    python tools/litaddr.py apply      # rewrite src/ to use the names (then build: all 13 must match)
    python tools/litaddr.py unnamed    # list literal addresses in src/ that have no name yet

Capcom's code reached many globals through fixed addresses (`*(u8 *)0x800C8660`, `((Effect *)0x800C3024)[i]`)
and the compiler + maspsx emit different machine code for a number than for a symbol (index register
order, CSE of the lui), so the matching C keeps the numbers. This tool keeps them too, but behind names:

    *(T *)0x800C8660            -> LIT(T, g_StageId)          = (*(T *)ADDR_g_StageId)
    ((Effect *)0x800C3024)      -> LITP(Effect, g_EffectPool)  = ((Effect *)ADDR_g_EffectPool)
    (T *)0x800C88A0  (no deref) -> LITP(T, g_OrderingTables)
    0x800C5158 (anything else)  -> ADDR_g_PlayerPosX
The preprocessor turns every form back into the same tokens (plus parentheses), so the build can't change.

config/addrs.txt: `0xADDRESS name [programs] # comment` - programs = comma list (main, shared, stage1,
title, ...) when the same number means different things in different programs; default = all.
"""
import os
import re
import sys
from collections import Counter

SPEC = os.path.join("config", "addrs.txt")
HEADER = os.path.join("include", "re1_addrs.h")
# main RAM 0x80xxxxxx and the scratchpad 0x1F800000..0x1F8003FF
NUM = r"0x((?:80[0-9A-Fa-f]{6})|(?:1[Ff]80[0-9A-Fa-f]{4}))[uU]?(?![\w])"
# not addresses: sign-bit masks; 0x800C0000 = an upper address half kept in a dead local for the match
NOT_ADDRESSES = {0x80000000, 0x80008000, 0x800C0000}
# C comments and string/char literals are copied unchanged
SKIP = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'', re.S)
TYPE = r"(?:(?:const|volatile|unsigned|signed|struct|union)\s+)*\w+(?:\s+\w+)?\s*(?:\*\s*)*"


def load_spec():
    """[(addr, name, programs or None, comment, scalar name or None)]
    `0xADDR name / scalar_name ...`: the second name is used where the code reads/writes the address as a
    plain number or pointer (`*(s32 *)0x1F8003D0` = LIT(s32, sp_vec_vx)), the first for the whole object
    (`(VECTOR *)0x1F8003D0` = LITP(VECTOR, sp_vec))."""
    out = []
    for line in open(SPEC, encoding="utf-8"):
        body, _, comment = line.partition("#")
        cols = body.split()
        if not cols:
            continue
        scalar = None
        if len(cols) > 3 and cols[2] == "/":
            scalar = cols[3]
            cols = cols[:2] + cols[4:]
        progs = set(cols[2].split(",")) if len(cols) > 2 else None
        out.append((int(cols[0], 16), cols[1], progs, comment.strip(), scalar))
    return out


def header():
    spec = load_spec()
    lines = ["/* GENERATED by tools/litaddr.py from config/addrs.txt - do not edit. */",
             "/* RAM addresses the matching C code writes as numbers (see tools/litaddr.py). */",
             "#ifndef RE1_ADDRS_H", "#define RE1_ADDRS_H", "",
             "/* the variable at a fixed address, read as type T / a T pointer to it */",
             "#define LIT(T, name) (*(T *)ADDR_##name)",
             "#define LITP(T, name) ((T *)ADDR_##name)", ""]
    seen = set()
    for addr, name, progs, comment, scalar in sorted(spec, key=lambda s: (s[0], s[1])):
        if name in seen:
            continue
        seen.add(name)
        note = comment + (f" [{','.join(sorted(progs))}]" if progs else "")
        lines.append(f"#define ADDR_{name} 0x{addr:08X}" + (f" /* {note} */" if note else ""))
        if scalar and scalar not in seen:
            seen.add(scalar)
            lines.append(f"#define ADDR_{scalar} 0x{addr:08X} /* = ADDR_{name}, read as a number */")
    lines += ["", "#endif", ""]
    open(HEADER, "w", newline="\n").write("\n".join(lines))
    print(f"wrote {HEADER}: {len(seen)} names")


def program(path):
    return path.replace(os.sep, "/").split("/")[1]


def name_for(spec, addr, prog, scalar=False):
    best = None
    for a, name, progs, _, sname in spec:
        if a == addr and (progs is None or prog in progs):
            if progs is not None or best is None:   # a program-specific name wins
                best = sname if scalar and sname else name
    return best


def is_scalar(t):
    """A dereference type that is a number or a pointer (not a struct/array object)."""
    t = re.sub(r"\b(volatile|const)\s+", "", t).strip()
    return t.endswith("*") or (t in BASE_TYPES and t != "void")


ADDR = NUM.replace("0x(", "0x(?P<addr>")
# words after which `*` / `(` start an expression (not an operand / function name)
EXPR_WORDS = {"return", "case", "else", "do"}
# `(type)` casts without a pointer that may stand before a dereference
BASE_TYPES = {"u8", "s8", "u16", "s16", "u32", "s32", "int", "char", "short", "long", "void", "u_long",
              "u_char", "u_short", "unsigned", "signed", "unsigned int", "unsigned char", "unsigned short"}


def before(code, i):
    """The token kind just before code[i]: 'operand' (identifier/number/`)`/`]`), 'call' (an identifier
    or keyword like `if` glued to a following `(`), or 'op' (operator, `(`, `,`, start)."""
    j = i - 1
    while j >= 0 and code[j] in " \t\n":
        j -= 1
    if j < 0:
        return "op"
    if code[j] == ")":
        # the `)` of a cast (`(u8 *)*p`) is followed by an expression, any other `)` ends an operand
        depth, k = 0, j
        while k >= 0:
            depth += {")": 1, "(": -1}.get(code[k], 0)
            if depth == 0:
                break
            k -= 1
        inner = code[k + 1:j].strip()
        if re.fullmatch(rf"{TYPE}\*", inner) or inner in BASE_TYPES:
            return "op"
        return "operand"
    if code[j] == "]":
        return "operand"
    if code[j].isalnum() or code[j] == "_":
        k = j
        while k >= 0 and (code[k].isalnum() or code[k] == "_"):
            k -= 1
        return "op" if code[k + 1:j + 1] in EXPR_WORDS else "operand"
    return "op"


def sub_ctx(pattern, fn, code):
    out, pos = [], 0
    for m in re.finditer(pattern, code):
        rep = fn(m, code)
        if rep is None:
            continue
        out.append(code[pos:m.start()])
        out.append(rep)
        pos = m.end()
    out.append(code[pos:])
    return "".join(out)


def rewrite(code, lookup):
    """Rewrite the literal addresses of a piece of code (no comments/strings in it)."""
    def name(m, scalar=False):
        return lookup(int(m.group("addr"), 16), scalar)

    def strip1(t):
        return re.sub(r"\s*\*\s*$", "", t.strip())

    # (*(T *)0xA): the parentheses may go only where they aren't a call's / keyword's own
    def deref_paren(m, code):
        t = strip1(m.group('t'))
        n = name(m, is_scalar(t))
        return f"LIT({t}, {n})" if n and before(code, m.start()) == "op" else None
    code = sub_ctx(rf"\(\s*\*\s*\((?P<t>{TYPE})\)\s*{ADDR}\s*\)", deref_paren, code)

    # *(T *)0xA where the * is a dereference (not a multiplication)
    def deref(m, code):
        t = strip1(m.group('t'))
        n = name(m, is_scalar(t))
        return f"LIT({t}, {n})" if n and before(code, m.start()) == "op" else None
    code = sub_ctx(rf"\*\s*\((?P<t>{TYPE})\)\s*{ADDR}", deref, code)

    # ((T *)0xA) and (T *)0xA
    def ptr_paren(m, code):
        n = name(m)
        return f"LITP({strip1(m.group('t'))}, {n})" if n and before(code, m.start()) == "op" else None
    code = sub_ctx(rf"\(\s*\((?P<t>{TYPE}\*)\)\s*{ADDR}\s*\)", ptr_paren, code)

    def ptr(m, code):
        n = name(m)
        return f"LITP({strip1(m.group('t'))}, {n})" if n else None
    code = sub_ctx(rf"\((?P<t>{TYPE}\*)\)\s*{ADDR}", ptr, code)

    # *LITP(T, n) left by an older run (a `*` after a cast was taken for a multiplication) = LIT(T, n)
    # (only when no postfix operator follows: in `*LITP(T, n)[i].x` the * applies to the whole `[i].x`)
    def deref_litp(m, code):
        depth, k = 1, m.end()
        while k < len(code) and depth:
            depth += {"(": 1, ")": -1}.get(code[k], 0)
            k += 1
        if re.match(r"\s*(\[|\.|->|\()", code[k:]):
            return None
        return "LIT(" if before(code, m.start()) == "op" else None
    code = sub_ctx(r"\*\s*LITP\(", deref_litp, code)

    # anything else: the bare number
    def bare(m, code):
        n = name(m)
        return f"ADDR_{n}" if n else None
    return sub_ctx(rf"(?<![\w.]){ADDR}", bare, code)


def files():
    for d, _, fs in os.walk("src"):
        for f in sorted(fs):
            if f.endswith((".c", ".h")):
                yield os.path.join(d, f)


def apply():
    spec = load_spec()
    changed = 0
    for p in files():
        prog = program(p)

        def lookup(addr, scalar=False):
            return None if addr in NOT_ADDRESSES else name_for(spec, addr, prog, scalar)
        text = open(p).read()
        out, pos = [], 0
        for m in SKIP.finditer(text):
            out.append(rewrite(text[pos:m.start()], lookup))
            out.append(m.group(0))
            pos = m.end()
        out.append(rewrite(text[pos:], lookup))
        new = "".join(out)
        if new != text:
            open(p, "w", newline="\n").write(new)
            changed += 1
    print(f"apply: {changed} files changed")


def unnamed():
    spec = load_spec()
    left = Counter()
    for p in files():
        prog = program(p)
        code = SKIP.sub("", open(p).read())
        for m in re.finditer(rf"(?<![\w.]){NUM}", code):
            a = int(m.group(1), 16)
            if a not in NOT_ADDRESSES and not name_for(spec, a, prog):
                left[(a, prog)] += 1
    for (a, prog), n in sorted(left.items()):
        print(f"0x{a:08X} {prog:<9} {n}")
    print(f"{sum(left.values())} uses of {len({a for a, _ in left})} unnamed addresses")


if __name__ == "__main__":
    {"header": header, "apply": apply, "unnamed": unnamed}[sys.argv[1] if len(sys.argv) > 1 else ""]()
