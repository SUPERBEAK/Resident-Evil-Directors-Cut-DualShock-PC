"""mergenames.py - turn per-address-range survey files into name lists for tools/rename.py.

Run from dualshock/ with the project venv python:
    python tools/mergenames.py ../temp/dc/hand/s1 ../temp/dc/hand/s2 ...

Reads survey.tsv (functions) and globals.tsv (globals) from each folder and writes
    config/names_main.txt     `func_X = name; // subsystem, confidence: evidence`
    config/globals_main.txt   `D_X = g_Name; // type guess, confidence: evidence`
sorted by address - reviewable lists that also document every name. Only high/medium
confidence names are active; low ones are written commented out (`// LOW func_X = name;`).
Rejected (and reported): invalid identifiers, C keywords, names already used somewhere in
src/include/config (e.g. Sony functions), duplicates (all copies rejected), globals inside the
player entity (0x800C5124-0x800C52A3: they become struct fields instead), and current names that
no longer exist (already renamed).
"""
import os
import re
import sys

KEYWORDS = set("""auto break case char const continue default do double else enum extern float for goto
if int long register return short signed sizeof static struct switch typedef union unsigned void
volatile while asm inline main""".split())
PLAYER_ENTITY = (0x800C5124, 0x800C52A4)


def read_tsv(path):
    rows = []
    if not os.path.isfile(path):
        return rows
    for line in open(path, encoding="utf-8", errors="replace"):
        cols = line.rstrip("\n").split("\t")
        if cols[0].lower().startswith("address") or len(cols) < 5:
            continue
        rows.append(cols)
    return rows


def existing_identifiers():
    ids = set()
    for top in ("src", "include", "config"):
        for d, _, fs in os.walk(top):
            for f in fs:
                if f.endswith((".c", ".h", ".txt")) and not f.startswith(("names_", "globals_")):
                    ids |= set(re.findall(r"\b[A-Za-z_]\w*\b", open(os.path.join(d, f), errors="replace").read()))
    return ids


def main():
    folders = sys.argv[1:]
    if not folders:
        sys.exit(__doc__)
    used = existing_identifiers()
    funcs, globs = [], []
    for f in folders:
        for c in read_tsv(os.path.join(f, "survey.tsv")):
            addr, cur, sub, new, conf = c[0], c[1], c[2], c[3], c[4]
            funcs.append((int(addr, 16), cur, new.strip(), conf.strip().lower(), sub, c[5] if len(c) > 5 else ""))
        for c in read_tsv(os.path.join(f, "globals.tsv")):
            addr, cur, new, ty, conf = c[0], c[1], c[2], c[3], c[4]
            globs.append((int(addr, 16), cur, new.strip(), conf.strip().lower(), ty, c[5] if len(c) > 5 else ""))

    def write(path, rows, is_glob):
        # several surveys may propose names for the same symbol: keep one proposal per symbol
        # (the higher confidence; equal names are just agreement)
        rank = {"high": 0, "medium": 1}
        best = {}
        for r in rows:
            k = (r[0], r[1])
            if k not in best or rank.get(r[3], 2) < rank.get(best[k][3], 2):
                best[k] = r
        rows = list(best.values())
        counts = {}
        for r in rows:
            counts[r[2]] = counts.get(r[2], 0) + 1
        out, rejected, active = [], [], 0
        out.append(f"// Generated by tools/mergenames.py from per-address-range survey files.")
        out.append("// Format: current = proposed; // subsystem or type, confidence: evidence")
        out.append("// Apply with: python tools/rename.py --file " + path.replace(os.sep, "/"))
        seen = set()
        for addr, cur, new, conf, info, ev in sorted(rows):
            if (addr, cur) in seen:
                continue
            seen.add((addr, cur))
            why = None
            if not re.match(r"^[A-Za-z_]\w*$", new) or new in KEYWORDS:
                why = "not a usable identifier"
            elif counts[new] > 1:
                why = "duplicate proposal"
            elif new in used:
                why = "name already used"
            elif cur not in used:
                why = "current name not found (renamed already?)"
            elif is_glob and PLAYER_ENTITY[0] <= addr < PLAYER_ENTITY[1]:
                why = "inside the player entity (struct field later)"
            ev = " ".join(ev.split())[:160]
            if why:
                rejected.append(f"0x{addr:08X} {cur} -> {new}: {why}")
                out.append(f"// REJECTED ({why}) {cur} = {new}; // {info}, {conf}: {ev}")
            elif conf not in ("high", "medium"):
                out.append(f"// LOW {cur} = {new}; // {info}, {conf}: {ev}")
            else:
                active += 1
                out.append(f"{cur} = {new}; // {info}, {conf}: {ev}")
        open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
        print(f"{path}: {active} active, {len(rejected)} rejected")
        for r in rejected[:40]:
            print("   ", r)
    write(os.path.join("config", "names_main.txt"), funcs, False)
    write(os.path.join("config", "globals_main.txt"), globs, True)


if __name__ == "__main__":
    main()
