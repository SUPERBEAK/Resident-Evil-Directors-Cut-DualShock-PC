"""permsetup.py - run decomp-permuter on a draft (random C rewrites for register allocation etc.).

Run from dualshock/ with the project venv python (through buildenv.sh):
    python tools/permsetup.py setup  <target> <func> [--file draft.c]
    python tools/permsetup.py check  <target> <func> <source.c>
    python tools/permsetup.py export <target> <func> <source.c>

setup  writes build/permuter/<target>/<func>/ for tools/external/decomp-permuter:
       base.c (the stored draft, or --file, preprocessed with -DPERMUTER), compile.sh (our
       cc1 -> maspsx -> as pipeline, then LINKED at the function's original address like
       refine.py, so fixed addresses and symbols compare correctly), target.o (the original
       function from its .s, built and linked the same way) and settings.toml.
       Then: venv python ../tools/external/decomp-permuter/permuter.py <dir> -j 8
check  compiles a permuter result (output-*/source.c) and compares the linked bytes with the
       original exactly (permuter ignores branch targets by default): prints MATCH or the distance.
export turns a matching result into a draft for integrate.py: the function plus the top-level
       declarations it uses (no typedefs/structs from the headers), written to
       build/auto/<target>/c/<func>.c with status `match` in results.json.
"""

import argparse
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import autodecomp as ad  # noqa: E402
import compiler_matrix as cm  # noqa: E402
import refine  # noqa: E402

PERMUTER = os.path.join(cm.TOOLS, "decomp-permuter")


def posix(p):
    """Windows path -> Git Bash path (compile.sh runs under bash); other systems: the absolute path."""
    p = os.path.abspath(p).replace("\\", "/")
    if not cm.WINDOWS:
        return p
    return re.sub(r"^([A-Za-z]):", lambda m: "/" + m.group(1).lower(), p)


def gcc_dir():
    return os.path.join(cm.TOOLS, "old-gcc-build", "gcc-2.6.3-psx")


def place_script(ctx, name, path):
    addr = ad.func_addr(ctx.func_dir, name)
    ro = refine.rodata_addr(ctx.func_dir, name)
    with open(path, "w") as f:
        f.write("SECTIONS {\n"
                f"  .text 0x{addr:08X} : {{ *(.text) }}\n"
                + (f"  .rodata 0x{ro:08X} : {{ *(.rodata) *(.rdata) }}\n" if ro else
                   "  .rodata : { *(.rodata) *(.rdata) }\n")
                + "  .data : { *(.data) *(.sdata) }\n  .bss : { *(.bss) *(.sbss) *(COMMON) }\n"
                  "  /DISCARD/ : { *(*) }\n}\n")


def cpp(src, out, defines):
    cm.run([os.path.join(gcc_dir(), "cpp" + cm.EXE), "-undef", "-nostdinc", "-P", "-Iinclude", "-D__GNUC__=2",
            "-Dmips", "-D__mips__", "-D_LANGUAGE_C", "-DLANGUAGE_C", *defines, src, out])


def setup(target, name, file):
    ctx = refine.Ctx(target)
    d = os.path.join("build", "permuter", target, name)
    os.makedirs(d, exist_ok=True)
    code = open(file or os.path.join("build", "auto", target, "c", f"{name}.c")).read().split("\n/* failed:")[0]
    o0 = "-O0" in ctx.flags.split()
    defs = ["-DPERMUTER"] + (["-DM2C_FIELD_STRUCT"] if o0 else [])
    tmp = os.path.join(d, "draft_full.c")
    open(tmp, "w", newline="\n").write(cm.preamble_for(code) + code)
    cpp(tmp, os.path.join(d, "base.c"), defs)
    place_script(ctx, name, os.path.join(d, "place.ld"))
    T = cm.TOOLS
    # compile.sh: `compile.sh in.c -o out.o` (called by the permuter through bash)
    script = f"""#!/bin/bash
# generated by dualshock/tools/permsetup.py - our compiler pipeline, linked at the original address
set -e
IN="$1"; OUT="$3"
"{posix(os.path.join(gcc_dir(), 'cc1' + cm.EXE))}" -quiet {ctx.flags} -mcpu=3000 -mips1 -fno-builtin -msoft-float "$IN" -o "$OUT.s" 2>/dev/null
"{posix(cm.PY)}" "{posix(os.path.join(T, 'maspsx', 'maspsx.py'))}" --aspsx-version=2.56 < "$OUT.s" > "$OUT.ms.s"
"{posix(os.path.join(cm.BIN, 'mips64-elf-as'))}" -EL -march=r3000 -mtune=r3000 -mabi=32 -no-pad-sections -O1 -G0 -I"{posix('include')}" -o "$OUT.tmp.o" "$OUT.ms.s"
"{posix(os.path.join(cm.BIN, 'mips64-elf-ld'))}" -EL -m elf32ebmip -nostdlib --no-check-sections --unresolved-symbols=ignore-all -T "{posix(ctx.syms)}" -T "{posix(os.path.join(d, 'place.ld'))}" -o "$OUT" "$OUT.tmp.o"
rm -f "$OUT.s" "$OUT.ms.s" "$OUT.tmp.o"
"""
    open(os.path.join(d, "compile.sh"), "w", newline="\n").write(script)
    # target.o: the original function (INCLUDE_ASM), built and linked the same way
    tc = os.path.join(d, "target_src.c")
    open(tc, "w", newline="\n").write(f'#include "common.h"\nINCLUDE_ASM("{ctx.func_dir.replace(os.sep, "/")}", {name});\n')
    cpp(tc, os.path.join(d, "target_src.i"), [])
    r = subprocess.run(["bash", os.path.join(d, "compile.sh"), os.path.join(d, "target_src.i"), "-o",
                        os.path.join(d, "target.o")], capture_output=True, text=True)
    if r.returncode:
        sys.exit("target build failed:\n" + r.stderr[-2000:])
    open(os.path.join(d, "settings.toml"), "w").write(
        f'func_name = "{name}"\ncompiler_type = "gcc"\n'
        # (the permuter is a Windows python: a C:/ path here, not the bash one)
        f'objdump_command = "{os.path.abspath(os.path.join(cm.BIN, "mips64-elf-objdump" + cm.EXE)).replace(os.sep, "/")} -drz -m mips:3000"\n')
    r = subprocess.run(["bash", os.path.join(d, "compile.sh"), os.path.join(d, "base.c"), "-o",
                        os.path.join(d, "base.o")], capture_output=True, text=True)
    print(f"{d}: {'base compiles' if r.returncode == 0 else 'BASE DOES NOT COMPILE'}")
    return d


def text_of(elf):
    return cm.read_elf(elf)[0][".text"][1]


def check(target, name, source):
    d = os.path.join("build", "permuter", target, name)
    out = os.path.join(d, "check.o")
    r = subprocess.run(["bash", os.path.join(d, "compile.sh"), source, "-o", out], capture_output=True, text=True)
    if r.returncode:
        print("does not compile")
        return None
    a, b = text_of(os.path.join(d, "target.o")), text_of(out)
    import struct
    wa = [struct.unpack_from("<I", a, i)[0] for i in range(0, len(a) - len(a) % 4, 4)]
    wb = [struct.unpack_from("<I", b, i)[0] for i in range(0, len(b) - len(b) % 4, 4)]
    d_ = refine.word_distance(wa, wb)
    print("MATCH" if d_ == 0 else f"distance {d_}")
    return d_


def draft_text(name, source):
    """The function from a permuter output plus the top-level declarations it uses (no
    typedefs/structs: those come from the headers - a hand draft's own typedef must be re-added)."""
    text = open(source).read()
    m = re.search(rf"^[^\n;{{}}]*\b{name}\s*\([^;{{]*\)\s*\{{", text, re.M)
    if not m:
        raise SystemExit("function definition not found")
    end = refine._close(text, text.index("{", m.end() - 1) - 0) if False else None
    depth, i = 0, text.index("{", m.start())
    while i < len(text):
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
        if depth == 0:
            break
    func = text[m.start():i]
    # the permuter writes `T f(args)` / `{` on two lines; integrate.py wants `T f(args) {`
    func = re.sub(r"\)\s*\n\{", ") {", func, count=1)
    used = set(re.findall(r"\b((?:D|func)_[0-9A-F]{8}\w*)\b", func))
    decls = []
    for line in text[:m.start()].split(";"):
        s = " ".join(line.split())
        if not s or s.startswith("typedef") or s.startswith("struct") or "{" in s or "}" in s:
            continue
        names = set(re.findall(r"\b((?:D|func)_[0-9A-F]{8}\w*)\b", s))
        if names & used:
            # function prototypes get m2c's marker: integrate.py drops marked prototypes of
            # functions the file already defines (m2c's guessed types would conflict)
            proto = re.match(r"^[^()]*\bfunc_[0-9A-F]{8}\s*\(", s) and not s.startswith("extern")
            decls.append(s + (";                            /* extern */" if proto else ";"))
    return "\n".join(decls) + "\n\n" + func + "\n"


def export(target, name, source):
    if check(target, name, source) != 0:
        sys.exit("not a byte-identical match - not exported")
    draft = draft_text(name, source)
    path = os.path.join("build", "auto", target, "c", f"{name}.c")
    open(path, "w", newline="\n").write(draft)
    rp = os.path.join("build", "auto", target, "results.json")
    res = json.load(open(rp))
    res[name] = "match"
    json.dump(res, open(rp, "w"), indent=1, sort_keys=True)
    print(f"exported to {path} (status match; run integrate.py --target {target})")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["setup", "check", "export"])
    ap.add_argument("target")
    ap.add_argument("func")
    ap.add_argument("source", nargs="?")
    ap.add_argument("--file")
    a = ap.parse_args()
    if a.cmd == "setup":
        setup(a.target, a.func, a.file)
    elif a.cmd == "check":
        check(a.target, a.func, a.source)
    else:
        export(a.target, a.func, a.source)


if __name__ == "__main__":
    main()
