"""api_table.py - the engine API table the overlays call through (0x801FE900).

Run from dualshock/ with the project venv python:  python tools/api_table.py [--md out.md]

func_80037014 (main program) copies 0xB7 (183) function pointers from D_800945BC (main data)
to RAM 0x801FE900. The overlays never call engine or Sony functions directly; they call
`*(0x801FE900 + 4*i)`, which splat shows as D_801FExxx. This prints, per table slot, the
target function and how often the overlays reference that slot.
"""

import argparse
import collections
import os
import re

TABLE_SRC = "g_OverlayApiTableSrc"   # (was D_800945BC before the renaming pass)
TABLE_RAM = 0x801FE900
COUNT = 0xB7
OVERLAYS = ["logo", "prologue", "title", "select", "ending"] + [f"stage{i}" for i in range(1, 8)]


def table_entries():
    text = open(os.path.join("asm", "main", "data", "data.data.s")).read()
    block = text.split(f"dlabel {TABLE_SRC}\n", 1)[1].split("enddlabel", 1)[0]
    words = re.findall(r"\.word (\S+)", block)
    return words[:COUNT]


def overlay_usage():
    use = collections.Counter()
    for o in OVERLAYS:
        for root, _, files in os.walk(os.path.join("asm", o)):
            for f in files:
                for m in re.findall(r"\bD_(801F[EF][0-9A-F]{3})\b", open(os.path.join(root, f)).read()):
                    use[int(m, 16)] += 1
    return use


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--md")
    args = ap.parse_args()
    entries = table_entries()
    use = overlay_usage()
    rows = []
    for i, target in enumerate(entries):
        addr = TABLE_RAM + 4 * i
        rows.append((i, addr, target, use.get(addr, 0)))
    for i, addr, target, n in rows:
        print(f"[{i:3d}] 0x{addr:08X} D_{addr:08X} -> {target:24s} used {n}x by overlays")
    extra = sorted(a for a in use if not TABLE_RAM <= a < TABLE_RAM + 4 * COUNT)
    print(f"\n{len(entries)} entries; other 0x801FExxx/0x801FFxxx addresses used by overlays: "
          + ", ".join(f"0x{a:08X}({use[a]})" for a in extra[:20]))
    if args.md:
        with open(args.md, "w", newline="\n") as f:
            f.write("# Overlay engine API table (0x801FE900)\n\n"
                    "Generated by `dualshock/tools/api_table.py`. `func_80037014` copies these 183 "
                    "function pointers from `D_800945BC` to RAM 0x801FE900; overlays call "
                    "`*(0x801FE900 + 4*i)` (splat: `D_801FExxx`), often as "
                    "`(D_801FEC18 = D_801FExxx)(...)`.\n\n"
                    "| Slot | RAM | Target | Overlay refs |\n|---|---|---|---|\n")
            for i, addr, target, n in rows:
                f.write(f"| {i} | 0x{addr:08X} | `{target}` | {n} |\n")
        print("wrote", args.md)


if __name__ == "__main__":
    main()
